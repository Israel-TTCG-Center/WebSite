/**
 * Compile-time recursive structural parity check between English (`en`) and Hebrew (`he`)
 * translation dictionaries. If any key is added or removed in one locale without the other,
 * `tsc` / `next build` fails immediately at compile time.
 */
type DeepStringShape<T> = {
  readonly [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends Record<string, unknown>
    ? DeepStringShape<T[K]>
    : never;
};

type EnTranslationShape = DeepStringShape<typeof translations.en>;
type HeTranslationShape = DeepStringShape<typeof translations.he>;

const _assertEnMatchesHe: EnTranslationShape = translations.he;
const _assertHeMatchesEn: HeTranslationShape = translations.en;
void _assertEnMatchesHe;
void _assertHeMatchesEn;

export function getLocalizedTitle(item: StoreItem, locale: Locale): string {
  if (locale === "he" && item.title_he) {
    return String(item.title_he);
  }
  return item.title;
}

export function getLocalizedDescription(
  item: StoreItem,
  locale: Locale
): string {
  if (locale === "he" && item.description_he) {
    return String(item.description_he);
  }
  return item.description;
}

export function getLocalizedBadge(
  item: StoreItem,
  locale: Locale
): string | undefined {
  if (locale === "he" && item.badge_he) {
    return String(item.badge_he);
  }
  return item.badge;
}

export function getLocalizedCategory(
  category: string,
  locale: Locale
): string {
  const dict = translations[locale].categories as Record<string, string>;
  return dict[category] || category;
}
